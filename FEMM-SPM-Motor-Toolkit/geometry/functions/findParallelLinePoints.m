function [x4, y4, x5, y5] = findParallelLinePoints(x6, y6, x7, y7, x901, y901, R)
    % Βρίσκει δύο σημεία σε παράλληλη ευθεία που ισαπέχουν R από σημείο αναφοράς
    %
    % Είσοδοι:
    %   x6, y6, x7, y7: Συντεταγμένες δύο σημείων που ορίζουν την αρχική ευθεία
    %   x901, y901: Συντεταγμένες σημείου αναφοράς
    %   R: Απόσταση από το σημείο αναφοράς
    %
    % Έξοδοι:
    %   x4, y4, x5, y5: Συντεταγμένες των δύο σημείων στην παράλληλη ευθεία
    % 10/2025 F.G.Kyrgios
    
    % Έλεγχος εάν τα σημεία P6 και P7 συμπίπτουν
    if x6 == x7 && y6 == y7
        error('Τα σημεία P6 και P7 συμπίπτουν - δεν ορίζουν ευθεία');
    end
    
    % Περίπτωση 1: Κατακόρυφη ευθεία (x6 = x7)
    if x6 == x7
        % Η παράλληλη ευθεία θα είναι x = x6 (ίδια απόσταση)
        x_parallel = x6;
        
        % Υπολογισμός y συντεταγμένων από την εξίσωση κύκλου
        discriminant = R^2 - (x_parallel - x901)^2;
        
        if discriminant < 0
            error('Δεν υπάρχουν σημεία τομής - η ακτίνα R είναι πολύ μικρή');
        end
        
        y4 = y901 + sqrt(discriminant);
        y5 = y901 - sqrt(discriminant);
        x4 = x_parallel;
        x5 = x_parallel;
        
        return;
    end
    
    % Περίπτωση 2: Γενική ευθεία (μην κατακόρυφη)
    
    % Υπολογισμός κλίσης m
    m = (y7 - y6) / (x7 - x6);
    
    % Υπολογισμός σταθερού όρου b για την αρχική ευθεία
    b_original = y6 - m * x6;
    
    % Η παράλληλη ευθεία περνάει από το σημείο αναφοράς (x901, y901)
    % με την ίδια κλίση m, άρα: y = m*x + b_parallel
    b_parallel = y901 - m * x901;
    
    % Εξίσωση κύκλου: (x - x901)^2 + (y - y901)^2 = R^2
    % Αντικαθιστώντας y = m*x + b_parallel:
    % (x - x901)^2 + (m*x + b_parallel - y901)^2 = R^2
    
    % Απλοποίηση της εξίσωσης
    A = 1 + m^2;
    B = 2*(m*(b_parallel - y901) - x901);
    C = x901^2 + (b_parallel - y901)^2 - R^2;
    
    % Υπολογισμός διαχωριστικής
    discriminant = B^2 - 4*A*C;
    
    if discriminant < 0
        error('Δεν υπάρχουν σημεία τομής - η ακτίνα R είναι πολύ μικρή');
    end
    
    % Επίλυση δευτεροβάθμιας εξίσωσης
    x4 = (-B + sqrt(discriminant)) / (2*A);
    x5 = (-B - sqrt(discriminant)) / (2*A);
    
    % Υπολογισμός αντίστοιχων y συντεταγμένων
    y4 = m * x4 + b_parallel;
    y5 = m * x5 + b_parallel;
end